def export_to_zotero(ref_list, output_path: str | Path) -> Path:
    """Export references for import into Zotero (.bib format)."""
    return export_bibtex(ref_list, output_path)


def export_to_mendeley(ref_list, output_path: str | Path) -> Path:
    """Export references for import into Mendeley (.ris format)."""
    return export_ris(ref_list, output_path)


# ══════════════════════════════════════════════════════════════
# Helper: parse reference text fields
# ══════════════════════════════════════════════════════════════

def _parse_ref_fields(text: str) -> dict[str, str]:
    """Extract structured fields from a reference text string."""
    fields = {}
    if not text:
        return fields

    # Extract DOI
    doi_match = re.search(r'(?:https?://)?(?:dx\.)?doi\.org/(.+?)(?:\s|$)', text, re.IGNORECASE)
    if doi_match:
        fields["doi"] = doi_match.group(1).rstrip(".")

    # Extract pages (xx-xx or xx-x format)
    pages_match = re.search(r',\s*(\d+[-–]\d+)\s*', text)
    if pages_match:
        fields["pages"] = pages_match.group(1)

    # Extract volume(issue)
    vi_match = re.search(r',?\s*(\d+)\((\d+)\)', text)
    if vi_match:
        fields["volume"] = vi_match.group(1)
        fields["issue"] = vi_match.group(2)
    else:
        vol_match = re.search(r',\s*(\d+),\s', text)
        if vol_match:
            fields["volume"] = vol_match.group(1)

    # Extract URL
    url_match = re.search(r'(https?://\S+)', text)
    if url_match:
        fields["url"] = url_match.group(1).rstrip(".")

    return fields
